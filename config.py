def validar():
    if not API_KEY or not API_SECRET: raise RuntimeError("Faltan ALPACA_API_KEY/ALPACA_API_SECRET.")
    if not (0 < RISK_PER_TRADE_PCT <= 1 and 0 < CRYPTO_RISK_PER_TRADE_PCT <= 1): raise RuntimeError("Riesgo por operación inválido.")
    if not (0 < STOP_LOSS_PCT < 1 and 0 < TAKE_PROFIT_PCT < 1 and 0 < TRAILING_STOP_PCT < 1): raise RuntimeError("Parámetros de salida inválidos.")
    if not (0 < MAX_TOTAL_EXPOSURE_PCT <= 1 and 0 < MAX_SINGLE_POSITION_PCT <= MAX_TOTAL_EXPOSURE_PCT): raise RuntimeError("Límites de exposición inválidos.")
    if not (0.10 <= ORDER_BUYING_POWER_BUFFER <= 0.99): raise RuntimeError("ORDER_BUYING_POWER_BUFFER inválido.")
    if not (0 <= CRYPTO_SCORE_MINIMO <= 100): raise RuntimeError("CRYPTO_SCORE_MINIMO inválido.")
    if EXECUTION_STREAM_RECONNECT_MIN_SECONDS <= 0 or EXECUTION_STREAM_RECONNECT_MAX_SECONDS < EXECUTION_STREAM_RECONNECT_MIN_SECONDS: raise RuntimeError("Intervalos del stream inválidos.")
    if DYNAMIC_EXIT_COOLDOWN_SECONDS < 0: raise RuntimeError("DYNAMIC_EXIT_COOLDOWN_SECONDS inválido.")
    if DYNAMIC_EXIT_MICROSTRUCTURE_MIN_SAMPLES < 1 or DYNAMIC_EXIT_MICROSTRUCTURE_WINDOW_SECONDS <= 0: raise RuntimeError("Parámetros de persistencia microestructura inválidos.")
    if not (-1.0 <= DYNAMIC_EXIT_MICROSTRUCTURE_IMBALANCE_THRESHOLD <= 1.0): raise RuntimeError("Umbral de imbalance inválido.")
    if DYNAMIC_EXIT_MICROSTRUCTURE_SPREAD_THRESHOLD_PCT <= 0: raise RuntimeError("Umbral de spread inválido.")
    if not (0 <= EARLY_SIGNAL_MIN_SCORE <= 100): raise RuntimeError("EARLY_SIGNAL_MIN_SCORE inválido.")
    if not (0 <= EARLY_SIGNAL_BASE_SCORE_FLOOR <= 100): raise RuntimeError("EARLY_SIGNAL_BASE_SCORE_FLOOR inválido.")
    if STOCK_UNIVERSE_REFRESH_MINUTES <= 0: raise RuntimeError("STOCK_UNIVERSE_REFRESH_MINUTES inválido.")
    return True
